// ─── 전체 시스템 프롬프트 조합 ───────────────────────

export function buildSystemPrompt(
  stage: StageCode,
  activityCode: ActivityCode,
  project: Pick<Project, 'title' | 'targetGradeGroup' | 'targetSubjects' | 'mode' | 'isA23Completed' | 'currentCycle'>,
  actorType: ActorType,
  learnerProfileSummary?: string,
  currentArtifact?: { title: string; content: Record<string, unknown>; status: string; version: number } | null,
  teamMembers?: string,
  confirmedArtifacts?: Record<string, { title: string; content: Record<string, unknown> }>,
  activityStatus?: string
): string {
  const activityMeta = ACTIVITY_META[activityCode]
  const isActiveReturn = activityStatus === 'active_return'

  // 현재 활동의 기존 산출물 내용 섹션
  const artifactSection = currentArtifact
    ? `\n## 현재 활동(${activityCode}) 기존 산출물 [반드시 참조]
제목: ${currentArtifact.title}
상태: ${isActiveReturn && currentArtifact.status === 'confirmed' ? 'confirmed → 재검토 중 (수정 가능)' : currentArtifact.status} (버전 ${currentArtifact.version})
내용:
${Object.entries(currentArtifact.content).map(([k, v]) => `  - ${k}: ${typeof v === 'string' ? v : JSON.stringify(v)}`).join('\n')}

${currentArtifact.status === 'confirmed'
  ? `⚠️ 이 산출물은 확정(confirmed) 상태입니다. 그러나 사용자가 수정을 요청하면 수정 가능합니다.
수정 요청 시: A안/B안으로 확인 → A안 선택 → 반드시 [ARTIFACT_UPDATE] 신호 포함.
사용자가 "수정하고 확정해달라"고 하면 → [ARTIFACT_UPDATE] + [ARTIFACT_CONFIRM] 함께 포함.
"확정됐으니 수정 불가"라고 하는 것은 절대 금지.`
  : `⚠️ 산출물 수정 시 반드시 위 기존 내용을 기준으로 변경 전/후를 비교하여 보여줄 것.`}
⚠️ 다른 활동의 산출물을 수정해야 하는 경우 [ARTIFACT_UPDATE@활동코드: 섹션=내용] 형식을 사용할 것.`
    : `\n## 현재 활동(${activityCode}) 산출물
아직 저장된 산출물이 없습니다. 이 활동의 결과물을 새로 작성합니다.`

  // 산출물 콘텐츠에서 AI 진행 안내 키 제거
  const ARTIFACT_NOISE_KEYS = ['다음 행동', '다음 단계', 'next step', 'ai 제안', '추천 사항', '참고 사항']
  function cleanArtifactContent(content: Record<string, unknown>) {
    return Object.fromEntries(
      Object.entries(content).filter(([k]) => !ARTIFACT_NOISE_KEYS.some(n => k.toLowerCase().includes(n)))
    )
  }

  // 이전 활동 확정 산출물 요약 (브리핑·맥락 파악용)
  const confirmedSection = confirmedArtifacts && Object.keys(confirmedArtifacts).length > 0
    ? `\n\n## 이전 활동 확정 산출물 [팀이 합의·확정한 결과 — 브리핑 요청 시 이 내용을 사용할 것]
${Object.entries(confirmedArtifacts)
  .filter(([code]) => code !== activityCode)
  .map(([code, a]) => {
    const cleaned = cleanArtifactContent(a.content)
    return `### ${code}: ${a.title}\n${Object.entries(cleaned).map(([k, v]) => `- ${k}: ${typeof v === 'string' ? v : JSON.stringify(v)}`).join('\n')}`
  })
  .join('\n\n')}`
    : ''

  const contextSection = `## 현재 컨텍스트
- 프로젝트: ${project.title}
- 학년군: ${project.targetGradeGroup}
- 융합 교과: ${project.targetSubjects?.join(', ') || '미지정'}
- 모드: ${project.mode === 'collaborative' ? '협력' : '단독'}
- 현재 단계: ${stage} > ${activityCode} (${activityMeta.label})
- 현재 주기: ${project.currentCycle}주기
${teamMembers ? `- 팀원 명단: ${teamMembers}
⚠️ 사용자 메시지는 [이름]: 내용 형식으로 전달됩니다. 반드시 실제 이름을 사용하세요. "(이름 A)", "닉네임 B" 등 자리표시자 절대 금지.` : ''}
${project.isA23Completed && learnerProfileSummary
  ? `\n## 가드레일 (A-2-3 학습자 프로필)\n${learnerProfileSummary}`
  : stage === 'Ds' ? '\n⚠️ A-2-3 학습자 프로필 미완성. 학습자 접근성 판단 주의.' : ''}${artifactSection}${confirmedSection}`

  const procedure = ACTIVITY_PROCEDURE[activityCode]
    ? `\n${ACTIVITY_PROCEDURE[activityCode]}`
    : ''

  const activityContext = ACTIVITY_CONTEXT[activityCode]
    ? `\n## 활동 특별 지시\n${ACTIVITY_CONTEXT[activityCode]}`
    : ''

  return [BASE_SYSTEM_PROMPT, contextSection, STAGE_PROMPTS[stage], procedure, activityContext].join('\n\n')
}
